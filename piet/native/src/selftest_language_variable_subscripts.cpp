struct Reply {
  std::string rc = "0";
  std::string msg;
  std::string text;  // every display block's text, concatenated
  std::string echo;  // every echo block's text (`scalar list` answers in one)
};

// The last whitespace-separated word of `s` (`scalar list`'s value column).
std::string trimmedTail(const std::string& s) {
  const size_t e = s.find_last_not_of(" \n");
  if (e == std::string::npos) return std::string();
  const size_t b = s.find_last_of(" ", e);
  return s.substr(b == std::string::npos ? 0 : b + 1, e - (b == std::string::npos ? 0 : b + 1) + 1);
}

Reply run(piet::SessionState& session, const std::string& cmd) {
  Reply r;
  try {
    for (const auto& b : piet::dispatch(cmd, session)) {
      if (!b.is_object()) continue;
      const std::string t = b.value("type", std::string());
      if (t == "error") {
        r.rc = piet::eval::coarseRc(b);
        r.msg += b.value("message", std::string());
      } else if (t == "display") {
        r.text += b.value("text", std::string());
      } else if (t == "echo") {
        r.echo += b.value("text", std::string());
      }
    }
  } catch (const std::exception& e) {
    r.rc = "EXC";
    r.msg = e.what();
  }
  return r;
}

// (1) The oracle replay.
void replayOracle(const std::string& workdir) {
  piet::SessionState s(workdir);
  const Reply g = run(s, "clear");
  (void)g;
  const Reply probe = run(s, "set obs 1");
  if (probe.rc != "0") {
    w2skip("W2I varsub oracle replay", "PRECONDITION: `set obs 1` failed (no engine), rc " +
                                           probe.rc);
    return;
  }
  auto r = piet::doexec::executeDoSource(kW2iSource, s, piet::dispatch);
  std::map<std::string, std::string> got;
  std::string precfail;
  for (const auto& b : r.blocks) {
    if (!b.is_object() || b.value("type", std::string()) != "display") continue;
    std::string t = b.value("text", std::string());
    while (!t.empty() && (t.back() == '\n' || t.back() == ' ')) t.pop_back();
    if (t.rfind("PREC|", 0) == 0) {
      const size_t bar = t.find('|', 5);
      if (bar != std::string::npos) got[t.substr(5, bar - 5)] = t;
    } else if (t.rfind("PRECFAIL|", 0) == 0) {
      precfail += (precfail.empty() ? "" : "; ") + t;
    }
  }
  w2check(!r.stoppedAtReason.has_value(),
          "W2I varsub: the w2i_varsub.do command stream runs to its end -- stopped: " +
              (r.stoppedAtReason ? *r.stoppedAtReason : std::string("no")));
  w2check(precfail.empty(), "W2I varsub: no PRECFAIL record (every PREC display ran at rc 0) -- "
                            "got " + (precfail.empty() ? std::string("none") : precfail));
  for (const W2iRecord& rec : kW2iRecords) {
    const std::string label = std::string("W2I varsub ") + rec.arm + " (w2i_varsub.log:" +
                              std::to_string(rec.logLine) + ")";
    const auto it = got.find(rec.arm);
    const std::string seen = it == got.end() ? std::string("(no record)") : it->second;
    w2check(seen == rec.want, label + ": " + rec.want + " -- got " + seen);
  }
}

