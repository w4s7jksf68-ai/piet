bool listed(const TrigramList& list, uint32_t gram) {
  int lo = 0, hi = kTrigrams - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    if (list.trigram[mid] == gram) return true;
    if (list.trigram[mid] < gram) lo = mid + 1; else hi = mid - 1;
  }
  return false;
}

// Score 0-98 of ASCII `bytes` against one trigram list.
int score(const std::string& bytes, const TrigramList& list) {
  uint32_t gram = 0;
  long count = 0, hits = 0;
  bool lastWasSpace = false;
  auto add = [&](unsigned char c) {
    gram = ((gram << 8) + c) & 0xFFFFFFu;
    ++count;
    if (listed(list, gram)) ++hits;
  };
  const size_t seen = bytes.size() < 8000 ? bytes.size() : 8000;
  for (size_t i = 0; i < seen; ++i) {
    const unsigned char b = static_cast<unsigned char>(bytes[i]);
    if (b == '\'') continue;
    unsigned char mapped = 0x20;
    if (b >= 'A' && b <= 'Z') mapped = static_cast<unsigned char>(b + 32);
    else if (b >= 'a' && b <= 'z') mapped = b;
    if (!(mapped == 0x20 && lastWasSpace)) add(mapped);
    lastWasSpace = mapped == 0x20;
  }
  add(0x20);
  const double share = static_cast<double>(hits) / static_cast<double>(count);
  if (share > 0.33) return 98;
  return static_cast<int>(share * 300.0);
}

