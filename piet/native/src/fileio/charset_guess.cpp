// The encoding Stata names in r(encoding) of `import delimited` when no
// encoding() was typed. Stata's detector is the ICU charset detector, and a file
// of plain ASCII is valid in every Latin set, so which one it names is decided
// by trigram statistics: the bank records ISO-8859-1, ISO-8859-2 and ISO-8859-9
// for different ASCII files, and the same file always the same name.
//
// Method, as measured against the bank's records (131 of 131 ASCII-only cells):
//   * Each candidate language has a list of its 64 most common letter trigrams
//     (the tables below are ICU's, adopted; register row in 40-ADOPTED-CODE.txt).
//     The text is lower-cased, every byte that is not a letter becomes a space,
//     apostrophes are dropped, runs of spaces collapse to one, a final space
//     closes the text, and each overlapping trigram that is in the list counts
//     as a hit. Only the first 8000 bytes are looked at.
//   * hits / trigrams is the raw share; above 0.33 the score is 98, otherwise
//     int(300 * share). A charset scores the best of its languages
//     (ISO-8859-1: en da de es fr it nl no pt sv; ISO-8859-2: cs hu pl ro;
//     ISO-8859-9: tr).
//   * UTF-8 scores 15 for text with no byte above 0x7F. The name reported is the
//     highest score; among equal scores the last of UTF-8, ISO-8859-1,
//     ISO-8859-2, ISO-8859-9 wins (a three-way tie is ISO-8859-9, a tie of
//     ISO-8859-1 and ISO-8859-2 is ISO-8859-2: bank cells 51e68a889eaac15a,
//     1efdda4b992c2070).
