std::string guessTextEncoding(const std::string& bytes, bool validUtf8) {
  bool plainAscii = true;
  for (char c : bytes)
    if (static_cast<unsigned char>(c) >= 0x80) { plainAscii = false; break; }
  if (!plainAscii) return validUtf8 ? "UTF-8" : "ISO-8859-1";
  static const char* const kNames[] = {"ISO-8859-1", "ISO-8859-2", "ISO-8859-9"};
  int best[3] = {0, 0, 0};
  for (const TrigramList& list : kLists) {
    const int s = score(bytes, list);
    if (s > best[list.charset]) best[list.charset] = s;
  }
  const char* name = "UTF-8";
  int top = 15;
  for (int c = 0; c < 3; ++c)
    if (best[c] > 0 && best[c] >= top) { top = best[c]; name = kNames[c]; }
  return name;
}

